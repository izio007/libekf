function out=nav_predict_reference(reference,T,model)
% Перенос положения опоры и его связи с навигационными ошибками в тех же осях.
% model: A, shift (м), Q (м²), t_start/t_end (с), frame_id, noise_independent.
assert(isstruct(reference)&&isscalar(reference)&& ...
    all(isfield(reference,{'position','covariance','cross_cov','t','frame_id'}))&& ...
    isstruct(model)&&isscalar(model)&& ...
    all(isfield(model,{'A','shift','Q','t_start','t_end','frame_id','noise_independent'})), ...
    'libekf:Peer','Incomplete reference propagation data.');
assert(isequal(model.noise_independent,true),'libekf:Correlation', ...
    'Reference process noise must be independent of prior errors and navigation process noise.');
assert(isnumeric(model.t_start)&&isnumeric(model.t_end)&& ...
    isscalar(model.t_start)&&isscalar(model.t_end)&& ...
    isreal([model.t_start model.t_end])&&all(isfinite([model.t_start model.t_end]))&& ...
    isscalar(reference.t)&&reference.t==model.t_start&&model.t_end>model.t_start&& ...
    strcmp(reference.frame_id,model.frame_id), ...
    'libekf:Epoch','Reference propagation must start at its epoch in the same frame.');
U=reference.cross_cov; V=reference.covariance; A=model.A; N=model.Q;
n=size(U,1);
assert(any(n==[21 42])&&isequal(size(U),[n 3])&&isreal(U)&&all(isfinite(U(:)))&& ...
    isequal(size(T),[n n])&&isreal(T)&&all(isfinite(T(:)))&& ...
    isequal(size(A),[3 3])&&isreal(A)&&all(isfinite(A(:)))&& ...
    isequal(size(reference.position),[3 1])&&isreal(reference.position)&&all(isfinite(reference.position))&& ...
    isequal(size(model.shift),[3 1])&&isreal(model.shift)&&all(isfinite(model.shift)), ...
    'libekf:Peer','Invalid reference geometry or navigation transition.');
for covariance={V,N}
    C=covariance{1};
    assert(isequal(size(C),[3 3])&&isreal(C)&&all(isfinite(C(:)))&& ...
        norm(C-C.','fro')<=1e-12*max(norm(C,'fro'),realmin)&&all(diag(C)>=0), ...
        'libekf:Covariance','Invalid reference covariance.');
    scales=sqrt(diag(C)); zero=scales==0;
    assert(all(all(C(zero,:)==0)),'libekf:Covariance','Zero variance has nonzero covariance.');
    scales(zero)=1; normalized=(C./scales)./scales.';
    values=eig((normalized+normalized.')/2);
    assert(min(values)>=-300*eps*max(1,max(abs(values))), ...
        'libekf:Covariance','Indefinite reference covariance.');
end
out=reference; out.position=A*reference.position+model.shift;
out.covariance=A*V*A.'+N; out.covariance=(out.covariance+out.covariance.')/2;
out.cross_cov=T*U*A.'; out.t=model.t_end;
assert(all(isfinite(out.position))&&all(isfinite(out.covariance(:)))&&all(isfinite(out.cross_cov(:))), ...
    'libekf:Covariance','Reference propagation overflow.');
% Независимость следующего измерения не наследуется от предыдущего.
if isfield(out,'noise_independent'), out=rmfield(out,'noise_independent'); end
end
