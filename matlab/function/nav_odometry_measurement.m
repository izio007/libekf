function obs=nav_odometry_measurement(a,b,m)
% Перемещение или направление движения камеры между двумя состояниями; H имеет 42 столбца.
required={'source','lineage','quality','noise_model','correlation_group','frame_id', ...
    't_start','t_end','t_received','units','z','R','camera_to_body','lever', ...
    'scale_valid','calibration_valid'};
for k=1:numel(required)
    assert(isfield(m,required{k}),'libekf:Packet',['Missing ' required{k}]);
end
mode='metric'; if isfield(m,'mode'), mode=m.mode; end
if strcmp(mode,'epipolar'), obs=epipolar_rows(a,b,m); return; end
if any(strcmp(mode,{'pose','direction_rotation'}))
    count=3; first_mode='metric';
    if strcmp(mode,'direction_rotation'), count=2; first_mode='direction'; end
    total=count+3; raw=m.R;
    assert(isnumeric(m.z)&&numel(m.z)==7&&all(isfinite(m.z(:)))&& ...
        iscell(m.units)&&numel(m.units)==total,'libekf:Dimension','Invalid paired camera observation.');
    assert(isequal(size(raw),[total total])&&all(isfinite(raw(:)))&& ...
        norm(raw-raw.','fro')<=1e-12*max(norm(raw,'fro'),realmin), ...
        'libekf:Covariance','Invalid full pose covariance.');
    [~,flag]=chol(raw); assert(flag==0,'libekf:Covariance','Invalid full pose covariance.');
    first=m; first.mode=first_mode; first.z=m.z(1:3);
    first.R=raw(1:count,1:count); first.units=m.units(1:count);
    second=m; second.mode='rotation'; second.z=m.z(4:7);
    second.R=raw(count+1:end,count+1:end); second.units=m.units(count+1:end);
    if isfield(m,'state_noise_cov')
        first=rmfield(first,'state_noise_cov'); second=rmfield(second,'state_noise_cov');
    end
    % Общий шум времён добавляется один раз после объединения направления и поворота.
    for name={'time_covariance','time_independent','time_linearization'}
        if isfield(first,name{1}), first=rmfield(first,name{1}); end
        if isfield(second,name{1}), second=rmfield(second,name{1}); end
    end
    one=nav_odometry_measurement(a,b,first); two=nav_odometry_measurement(a,b,second);
    obs=one; obs.predicted=[one.predicted;two.predicted];
    obs.residual=[one.residual;two.residual]; obs.H=[one.H;two.H];
    obs.noise_transform=blkdiag(one.noise_transform,two.noise_transform);
    obs.R=obs.noise_transform*raw*obs.noise_transform.'; obs.R=(obs.R+obs.R.')/2;
    obs.units=m.units; obs=attach_dependence(obs,m); obs=attach_time(obs,a,b,m); return;
end
assert(any(strcmp(mode,{'metric','direction','rotation'})),'libekf:Model','Unknown odometry mode.');
assert(strcmp(m.quality,'VALID') && ...
    (~strcmp(mode,'metric')||isequal(m.scale_valid,true)) && ...
    isequal(m.calibration_valid,true),'libekf:Quality','Valid metric scale and calibration required.');
assert(strcmp(a.frame_id,b.frame_id)&&strcmp(m.frame_id,a.frame_id), ...
    'libekf:Frame','Both states must share a local frame.');
assert(isscalar(m.t_start)&&isscalar(m.t_end)&&isscalar(m.t_received)&& ...
    all(isfinite([m.t_start m.t_end m.t_received]))&& ...
    m.t_start==a.t&&m.t_end==b.t&&b.t>a.t&&m.t_received>=b.t, ...
    'libekf:Epoch','Invalid image pair times.');
assert(ischar(m.source)&&~isempty(m.source)&&iscell(m.lineage)&&~isempty(m.lineage)&& ...
    all(cellfun(@(x)ischar(x)&&~isempty(x),m.lineage))&& ...
    ischar(m.correlation_group)&&~isempty(m.correlation_group)&& ...
    any(strcmp(m.noise_model,{'independent','joint_required'})), ...
    'libekf:Lineage','Missing provenance or dependence declaration.');
units={'m';'m';'m'}; dimension=3; zdimension=3;
if strcmp(mode,'rotation'), units={'rad';'rad';'rad'}; zdimension=4; end
if strcmp(mode,'direction'), units={'1';'1'}; dimension=2; end
assert(iscell(m.units)&&isequal(m.units(:),units), ...
    'libekf:Units','Invalid displacement or tangent-plane units.');
D=m.camera_to_body; l=m.lever(:); z=m.z(:);
assert(isnumeric(D)&&isequal(size(D),[3 3])&&all(isfinite(D(:)))&& ...
    norm(D.'*D-eye(3),'fro')<1e-10&&abs(det(D)-1)<1e-10&& ...
    isnumeric(l)&&numel(l)==3&&all(isfinite(l))&& ...
    isnumeric(z)&&numel(z)==zdimension&&all(isfinite(z)), ...
    'libekf:Geometry','Invalid camera geometry or displacement.');
noise_transform=eye(dimension);
R=m.R;
assert(isequal(size(R),[dimension dimension])&&all(isfinite(R(:)))&& ...
    norm(R-R.','fro')<=1e-12*max(norm(R,'fro'),realmin), ...
    'libekf:Covariance','Invalid displacement covariance.');
[~,flag]=chol(R); assert(flag==0,'libekf:Covariance','Positive covariance required.');
A=nav_rotation(a.q); B=nav_rotation(b.q);
delta=b.p(:)-a.p(:)+B*l-A*l; v=A.'*delta; h=D.'*v;
H=zeros(3,42); H(:,1:3)=-D.'*A.'; H(:,22:24)=D.'*A.';
H(:,7:9)=D.'*nav_skew(v+l); H(:,28:30)=-D.'*A.'*B*nav_skew(l);
if strcmp(mode,'direction')
    for name={'tangent_basis','min_displacement','max_angle'}
        assert(isfield(m,name{1}),'libekf:Packet',['Missing ' name{1}]);
    end
    E=m.tangent_basis; length=norm(h);
    assert(abs(norm(z)-1)<1e-10 && isequal(size(E),[3 2]) && all(isfinite(E(:))) && ...
        norm(E.'*E-eye(2),'fro')<1e-10 && norm(E.'*z)<1e-10 && ...
        isscalar(m.min_displacement)&&isfinite(m.min_displacement)&&m.min_displacement>0 && ...
        isscalar(m.max_angle)&&isfinite(m.max_angle)&&m.max_angle>0&&m.max_angle<pi/2, ...
        'libekf:Geometry','Invalid direction or tangent-plane domain.');
    assert(length>m.min_displacement,'libekf:Geometry','Translation direction undefined.');
    direction=h/length;
    assert(z.'*direction>=cos(m.max_angle),'libekf:Geometry','Outside local angular domain.');
    H=E.'*(eye(3)-direction*direction.')/length*H;
    h=E.'*direction; z=E.'*z;
end
if strcmp(mode,'rotation')
    assert(isfield(m,'max_angle')&&isscalar(m.max_angle)&&isfinite(m.max_angle)&& ...
        m.max_angle>0&&m.max_angle<pi,'libekf:Geometry','Specify local rotation domain.');
    relative=D.'*A.'*B*D; measured=nav_rotation(z);
    errorq=nav_quaternion(relative.'*measured);
    if errorq(1)<0, errorq=-errorq; end
    sine=norm(errorq(2:4)); angle=2*atan2(sine,errorq(1));
    assert(angle<=m.max_angle,'libekf:Geometry','Outside local rotation domain.');
    if sine<1e-12, residual=2*errorq(2:4); else, residual=angle/sine*errorq(2:4); end
    V=nav_skew(residual);
    if angle<1e-4, coefficient=1/12+angle^2/720; ...
    else, coefficient=(1-.5*angle/tan(.5*angle))/angle^2; end
    left=eye(3)-.5*V+coefficient*(V*V);
    right=eye(3)+.5*V+coefficient*(V*V);
    H=zeros(3,42); H(:,7:9)=-left*relative.'*D.'; H(:,28:30)=left*D.';
    noise_transform=right; R=right*R*right.'; R=(R+R.')/2;
    h=nav_quaternion(relative);
else
    residual=z-h;
end
assert(all(isfinite(h))&&all(isfinite(H(:))),'libekf:Geometry','Invalid state geometry.');
obs=struct('noise_transform',noise_transform,'predicted',h,'residual',residual,'H',H,'R',R, ...
    'units',{m.units},'frame_id',m.frame_id,'t_start',a.t,'t_end',b.t, ...
    't_received',m.t_received,'source',m.source,'lineage',{m.lineage}, ...
    'noise_model',m.noise_model,'correlation_group',m.correlation_group);
obs=attach_dependence(obs,m); obs=attach_time(obs,a,b,m);
end

function obs=attach_dependence(obs,m)
if isfield(m,'state_noise_cov')
    U=m.state_noise_cov;
    assert(isfield(m,'state_noise_frame_id')&&strcmp(m.state_noise_frame_id,obs.frame_id)&& ...
        isequal(size(U),[42 size(obs.noise_transform,2)])&&all(isfinite(U(:))), ...
        'libekf:Correlation','Camera cross covariance must cover both epoch errors.');
    obs.state_noise_cov=U*obs.noise_transform.';
end
end

function obs=attach_time(obs,a,b,m)
names={'time_covariance','time_independent','time_linearization'};
if ~any(isfield(m,names)), return; end
assert(all(isfield(m,names))&&isequal(m.time_independent,true), ...
    'libekf:Correlation','Time errors must be independent of state and original observation noise.');
C=m.time_covariance; timing=m.time_linearization;
assert(isnumeric(C)&&isreal(C)&&isequal(size(C),[2 2])&&all(isfinite(C(:)))&& ...
    norm(C-C.','fro')<=1e-12*max(norm(C,'fro'),realmin)&&all(diag(C)>=0), ...
    'libekf:Covariance','Expected covariance of two image times in seconds squared.');
scale=sqrt(diag(C)); zero=scale==0;
assert(~any(any(C(zero,:)~=0)),'libekf:Covariance','Impossible time covariance.');
normalized=(C(~zero,~zero)./scale(~zero))./scale(~zero).';
assert(isempty(normalized)||min(eig((normalized+normalized.')/2))>=-1e-12, ...
    'libekf:Covariance','Indefinite time covariance.');
assert(isstruct(timing)&&isscalar(timing)&&all(isfield(timing, ...
    {'body_rates','epochs','unit','reference','valid'}))&&isequal(timing.valid,true)&& ...
    strcmp(timing.unit,'rad/s')&&strcmp(timing.reference,'earth')&& ...
    isnumeric(timing.epochs)&&isequal(timing.epochs(:),[a.t;b.t])&& ...
    isnumeric(timing.body_rates)&&isreal(timing.body_rates)&&isequal(size(timing.body_rates),[3 2])&& ...
    all(isfinite(timing.body_rates(:))), 'libekf:Time','Valid Earth-relative body rates at both image epochs required.');
% H уже учитывает ориентацию камеры, плечо установки и выбранные компоненты наблюдения.
rates=zeros(42,2); rates(1:3,1)=a.v(:); rates(7:9,1)=timing.body_rates(:,1);
rates(22:24,2)=b.v(:); rates(28:30,2)=timing.body_rates(:,2);
obs.time_jacobian=obs.H*rates;
obs.R=obs.R+obs.time_jacobian*C*obs.time_jacobian.'; obs.R=(obs.R+obs.R.')/2;
end

function obs=epipolar_rows(a,b,m)
% Неизвестная глубина исключена условием пересечения двух лучей.
assert(all(isfield(m,{'intrinsics','row_motion','matches_valid','scene_static'})), ...
    'libekf:Packet','Missing timed correspondence model.');
assert(strcmp(m.quality,'VALID')&&isequal(m.calibration_valid,true)&& ...
    isequal(m.matches_valid,true)&&isequal(m.scene_static,true), ...
    'libekf:Quality','Validated static-scene correspondences required.');
assert(strcmp(a.frame_id,b.frame_id)&&strcmp(m.frame_id,a.frame_id)&& ...
    isscalar(m.t_start)&&isscalar(m.t_end)&&isscalar(m.t_received)&& ...
    m.t_start==a.t&&m.t_end==b.t&&b.t>a.t&&isfinite(m.t_received)&&m.t_received>=b.t, ...
    'libekf:Epoch','Invalid paired epochs.');
assert(ischar(m.source)&&~isempty(m.source)&&iscell(m.lineage)&&~isempty(m.lineage)&& ...
    all(cellfun(@(x)ischar(x)&&~isempty(x),m.lineage))&& ...
    ischar(m.correlation_group)&&~isempty(m.correlation_group)&& ...
    any(strcmp(m.noise_model,{'independent','joint_required'})), ...
    'libekf:Lineage','Missing provenance or dependence model.');
assert(~any(isfield(m,{'time_covariance','time_independent','time_linearization'})), ...
    'libekf:Correlation','Point times already belong to the full input covariance.');
z=m.z; K=m.intrinsics; D=m.camera_to_body; lever=m.lever(:); motion=m.row_motion;
assert(isnumeric(z)&&isreal(z)&&size(z,2)==6&&size(z,1)>=1&&all(isfinite(z(:))), ...
    'libekf:Dimension','Expected rows x1,y1,t1,x2,y2,t2.');
n=size(z,1); dimension=6*n+6;
expected=[repmat({'pixel';'pixel';'s';'pixel';'pixel';'s'},n,1);repmat({'rad/s'},6,1)];
acceleration=zeros(3,2);
accelerated=isstruct(motion)&&any(isfield(motion, ...
    {'acceleration','acceleration_unit','acceleration_frame_id','acceleration_valid'}));
if accelerated
    assert(isscalar(motion)&&all(isfield(motion, ...
        {'acceleration','acceleration_unit','acceleration_frame_id','acceleration_valid'}))&& ...
        isnumeric(motion.acceleration)&&isreal(motion.acceleration)&& ...
        isequal(size(motion.acceleration),[3 2])&&all(isfinite(motion.acceleration(:)))&& ...
        strcmp(motion.acceleration_unit,'m/s^2')&&strcmp(motion.acceleration_frame_id,a.frame_id)&& ...
        isequal(motion.acceleration_valid,true), ...
        'libekf:Acceleration','Prepared Earth-relative local acceleration required.');
    acceleration=motion.acceleration; dimension=dimension+6;
    expected=[expected;repmat({'m/s^2'},6,1)];
end
assert(iscell(m.units)&&isequal(m.units(:),expected),'libekf:Units','Invalid timed ray units.');
assert(isequal(size(K),[3 3])&&isreal(K)&&all(isfinite(K(:)))&& ...
    isequal(K(3,:),[0 0 1])&&K(2,1)==0&&K(1,1)>0&&K(2,2)>0&& ...
    isequal(size(D),[3 3])&&all(isfinite(D(:)))&&norm(D.'*D-eye(3),'fro')<1e-10&& ...
    abs(det(D)-1)<1e-10&&numel(lever)==3&&all(isfinite(lever)), ...
    'libekf:Geometry','Invalid camera calibration or installation.');
assert(isstruct(motion)&&isscalar(motion)&&all(isfield(motion, ...
    {'body_rates','epochs','unit','reference','valid','bias_included','max_offset','min_baseline'}))&& ...
    isequal(motion.valid,true)&&isequal(motion.bias_included,true)&&strcmp(motion.unit,'rad/s')&&strcmp(motion.reference,'earth')&& ...
    isequal(motion.epochs(:),[a.t;b.t])&&isequal(size(motion.body_rates),[3 2])&& ...
    isreal(motion.body_rates)&&all(isfinite(motion.body_rates(:)))&& ...
    isscalar(motion.max_offset)&&isfinite(motion.max_offset)&&motion.max_offset>0&& ...
    isscalar(motion.min_baseline)&&isfinite(motion.min_baseline)&&motion.min_baseline>0, ...
    'libekf:Time','Explicit short-interval motion model required.');
assert(all(abs(z(:,3)-a.t)<=motion.max_offset)&&all(abs(z(:,6)-b.t)<=motion.max_offset)&& ...
    all(z(:,3)<=m.t_received)&&all(z(:,6)<=m.t_received), ...
    'libekf:Time','Point time outside the valid motion interval.');
C=m.R;
assert(isequal(size(C),[dimension dimension])&&isreal(C)&&all(isfinite(C(:)))&& ...
    norm(C-C.','fro')<=1e-12*max(norm(C,'fro'),realmin)&&all(diag(C)>=0), ...
    'libekf:Covariance','Full coordinate/time/rate covariance required.');
scale=sqrt(diag(C)); zero=scale==0;
assert(~any(any(C(zero,:)~=0)),'libekf:Covariance','Impossible zero-variance dependence.');
normalized=(C(~zero,~zero)./scale(~zero))./scale(~zero).';
assert(isempty(normalized)||min(eig(full((normalized+normalized.')/2)))>=-100*eps*dimension, ...
    'libekf:Covariance','Indefinite raw ray covariance.');
f=zeros(n,1); H=zeros(n,42); G=zeros(n,dimension);
for k=1:n
    one=row_ray(a,z(k,1:3),motion.body_rates(:,1),K,D,lever,acceleration(:,1));
    two=row_ray(b,z(k,4:6),motion.body_rates(:,2),K,D,lever,acceleration(:,2));
    delta=two.position-one.position;
    assert(norm(delta)>motion.min_baseline,'libekf:Geometry','Ray baseline is undefined.');
    g=cross(one.ray,two.ray); first_ray=cross(two.ray,delta); second_ray=cross(delta,one.ray);
    f(k)=g.'*delta;
    H(k,1:21)=-g.'*one.position_state+first_ray.'*one.ray_state;
    H(k,22:42)=g.'*two.position_state+second_ray.'*two.ray_state;
    G(k,6*k-5:6*k)=[-g.'*one.position_input+first_ray.'*one.ray_input, ...
        g.'*two.position_input+second_ray.'*two.ray_input];
    G(k,6*n+1:6*n+3)=-g.'*one.position_rate+first_ray.'*one.ray_rate;
    G(k,6*n+4:6*n+6)=g.'*two.position_rate+second_ray.'*two.ray_rate;
    if accelerated
        G(k,6*n+7:6*n+9)=-g.'*one.position_acceleration;
        G(k,6*n+10:6*n+12)=g.'*two.position_acceleration;
    end
end
R=G*C*G.'; R=(R+R.')/2;
assert(all(isfinite(f))&&all(isfinite(H(:)))&&all(isfinite(R(:))), ...
    'libekf:Geometry','Nonfinite timed ray observation.');
obs=struct('predicted',f,'residual',-f,'H',H,'R',R,'noise_transform',-G, ...
    'units',{repmat({'m'},n,1)},'frame_id',m.frame_id,'t_start',a.t,'t_end',b.t, ...
    't_received',m.t_received,'source',m.source,'lineage',{m.lineage}, ...
    'noise_model',m.noise_model,'correlation_group',m.correlation_group);
obs=attach_dependence(obs,m);
if isfield(m,'state_noise_cov')
    obs.input_noise_cov=m.R; obs.state_input_cov=m.state_noise_cov;
end
end

function out=row_ray(s,measurement,rate,K,D,lever,acceleration)
tau=measurement(3)-s.t; w=rate-s.bg(:); phi=w*tau; V=nav_skew(phi); angle=norm(phi);
if angle<1e-4
    Jr=eye(3)-.5*V+(1/6)*(V*V);
else
    Jr=eye(3)-(1-cos(angle))/angle^2*V+(angle-sin(angle))/angle^3*(V*V);
end
Q=nav_rotation(s.q); E=expm(V); A=Q*E;
pixel=K\[measurement(1:2).';1]; ray_body=D*pixel;
out.position=s.p(:)+s.v(:)*tau+.5*acceleration*tau^2+A*lever; out.ray=A*ray_body;
out.position_state=zeros(3,21); out.ray_state=zeros(3,21);
out.position_state(:,1:3)=eye(3); out.position_state(:,4:6)=tau*eye(3);
out.position_state(:,7:9)=-Q*nav_skew(E*lever);
out.ray_state(:,7:9)=-Q*nav_skew(E*ray_body);
out.position_rate=-A*nav_skew(lever)*Jr*tau;
out.ray_rate=-A*nav_skew(ray_body)*Jr*tau;
out.position_state(:,13:15)=-out.position_rate; out.ray_state(:,13:15)=-out.ray_rate;
out.position_acceleration=.5*tau^2*eye(3);
out.position_input=[zeros(3,2) s.v(:)+acceleration*tau+A*nav_skew(w)*lever];
out.ray_input=[A*D*(K\[eye(2);zeros(1,2)]) A*nav_skew(w)*ray_body];
end
