function result=nav_inertial_camera_motion(states,P,raw,env,limits)
% Подготовить земные угловые скорости и ускорения для двух опор камеры.
% raw.covariance: дисперсии отсчётов [accel1;gyro1;accel2;gyro2], не спектральная плотность.
assert(iscell(states)&&numel(states)==2,'libekf:State','Expected two navigation states.');
a=states{1}; b=states{2};
assert(strcmp(a.frame_id,b.frame_id)&&strcmp(a.frame_id,env.frame_id)&& ...
    isfinite(a.t)&&isfinite(b.t)&&a.t<b.t,'libekf:Epoch','Invalid paired frames or epochs.');
assert(isstruct(raw)&&isscalar(raw)&&all(isfield(raw,{'accel','gyro','epochs','t_received', ...
    'covariance','state_noise_cov','state_noise_frame_id','quality','calibration_valid', ...
    'frame','accel_unit','gyro_unit','source','lineage','lineage_times'})), ...
    'libekf:Packet','Incomplete paired inertial observations.');
assert(strcmp(raw.quality,'VALID')&&isequal(raw.calibration_valid,true), ...
    'libekf:Quality','Usable calibrated inertial samples required.');
assert(strcmp(raw.frame,'BODY')&&strcmp(raw.accel_unit,'m/s^2')&&strcmp(raw.gyro_unit,'rad/s')&& ...
    strcmp(raw.state_noise_frame_id,a.frame_id),'libekf:Units','Invalid inertial units or covariance axes.');
source_epochs=raw.epochs(:); interpolation=[];
if isfield(raw,'interpolation_error')
    [raw,interpolation,source_epochs]=interpolate_samples(raw,[a.t;b.t],P,limits);
end
assert(isnumeric(raw.accel)&&isreal(raw.accel)&&isequal(size(raw.accel),[3 2])&&all(isfinite(raw.accel(:)))&& ...
    isnumeric(raw.gyro)&&isreal(raw.gyro)&&isequal(size(raw.gyro),[3 2])&&all(isfinite(raw.gyro(:)))&& ...
    isequal(raw.epochs(:),[a.t;b.t])&&isscalar(raw.t_received)&&isfinite(raw.t_received)&&raw.t_received>=b.t, ...
    'libekf:Time','Inertial sample epochs must match camera reference states.');
assert(ischar(raw.source)&&isrow(raw.source)&&~isempty(raw.source)&&iscell(raw.lineage)&& ...
    numel(raw.lineage)==numel(source_epochs)&&all(cellfun(@(x)ischar(x)&&isrow(x)&&~isempty(x),raw.lineage))&& ...
    numel(unique(raw.lineage))==numel(source_epochs)&&isequal(raw.lineage_times(:),source_epochs), ...
    'libekf:Lineage','Original inertial sample identities and epochs required.');
assert(isscalar(limits.max_offset)&&isfinite(limits.max_offset)&&limits.max_offset>0&& ...
    isscalar(limits.min_baseline)&&isfinite(limits.min_baseline)&&limits.min_baseline>0, ...
    'libekf:Time','Explicit local motion validity limits required.');
R=raw.covariance; U=raw.state_noise_cov;
assert(isequal(size(P),[42 42])&&isequal(size(R),[12 12])&&isequal(size(U),[42 12]), ...
    'libekf:Covariance','Invalid joint state and sample covariance dimensions.');
joint=[P U;U.' R];
assert(isreal(joint)&&all(isfinite(joint(:)))&& ...
    norm(joint-joint.','fro')<=1e-12*max(norm(joint,'fro'),realmin)&&all(diag(joint)>=0), ...
    'libekf:Covariance','Invalid joint state and sample covariance.');
scale=sqrt(diag(joint)); zero=scale==0;
assert(~any(any(joint(zero,:)~=0)),'libekf:Covariance','Impossible zero-variance dependence.');
scale(zero)=1; normalized=(joint./scale)./scale.';
assert(min(eig((normalized+normalized.')/2))>=-100*eps*54, ...
    'libekf:Covariance','Indefinite state/sample covariance.');
omega=env.Omega(:); gravity=env.gravity_origin(:); gradient=env.gravity_gradient;
assert(numel(omega)==3&&isreal(omega)&&all(isfinite(omega))&& ...
    numel(gravity)==3&&isreal(gravity)&&all(isfinite(gravity))&& ...
    isequal(size(gradient),[3 3])&&isreal(gradient)&&all(isfinite(gradient(:)))&& ...
    isscalar(env.gravity_radius)&&isfinite(env.gravity_radius)&&env.gravity_radius>0, ...
    'libekf:Gravity','Invalid local Earth and gravity model.');
A=zeros(12,42); B=zeros(12); rates=zeros(3,2); acceleration=zeros(3,2); O=nav_skew(omega);
for j=1:2
    s=states{j}; C=nav_rotation(s.q);
    assert(all(cellfun(@(name)isnumeric(s.(name))&&isreal(s.(name))&&numel(s.(name))==3&& ...
        all(isfinite(s.(name)(:))),{'p','v','ba','bg'}))&&norm(s.p)<=env.gravity_radius, ...
        'libekf:State','Invalid state or gravity domain.');
    force=raw.accel(:,j)-s.ba(:); earth_body=C.'*omega;
    rates(:,j)=raw.gyro(:,j)-earth_body;
    acceleration(:,j)=C*force+gravity+gradient*s.p(:)-2*O*s.v(:);
    state_columns=(j-1)*21+(1:21); input_columns=(j-1)*6+(1:6);
    rate_rows=(j-1)*3+(1:3); accel_rows=6+rate_rows;
    Ar=zeros(3,21); Ar(:,7:9)=nav_skew(earth_body);
    Aa=zeros(3,21); Aa(:,1:3)=-gradient; Aa(:,4:6)=2*O;
    Aa(:,7:9)=C*nav_skew(force); Aa(:,10:12)=C;
    A(rate_rows,state_columns)=Ar; A(accel_rows,state_columns)=Aa;
    B(rate_rows,input_columns(4:6))=eye(3); B(accel_rows,input_columns(1:3))=C;
end
% Ошибка подготовленного входа = A*ошибка состояния + B*шум исходного отсчёта.
covariance=A*P*A.'+B*R*B.'+A*U*B.'+B*U.'*A.';
covariance=(covariance+covariance.')/2;
cross=P*A.'+U*B.';
motion=struct('body_rates',rates,'epochs',[a.t b.t],'unit','rad/s','reference','earth', ...
    'valid',true,'bias_included',true,'max_offset',limits.max_offset,'min_baseline',limits.min_baseline, ...
    'acceleration',acceleration,'acceleration_unit','m/s^2','acceleration_frame_id',a.frame_id, ...
    'acceleration_valid',true);
result=struct('motion',motion,'covariance',covariance,'state_noise_cov',cross, ...
    'state_transform',A,'input_transform',B,'lineage',{raw.lineage},'lineage_times',raw.lineage_times, ...
    'input_sources',{{raw.source}},'t_received',raw.t_received,'noise_model','joint_required');
if ~isempty(interpolation)
    result.input_transform=B*interpolation;
    result.interpolation_transform=B;
end
end

function [out,L,source_epochs]=interpolate_samples(raw,targets,P,limits)
times=raw.epochs(:); count=numel(times); error_model=raw.interpolation_error;
assert(count>=2&&isnumeric(times)&&isreal(times)&&all(isfinite(times))&&all(diff(times)>0)&& ...
    all(targets>=times(1)&targets<=times(end))&&isscalar(raw.t_received)&&isfinite(raw.t_received)&& ...
    raw.t_received>=times(end)&&isfield(limits,'max_sample_gap')&& ...
    isscalar(limits.max_sample_gap)&&isfinite(limits.max_sample_gap)&&limits.max_sample_gap>0, ...
    'libekf:Time','Bracketing inertial samples and an explicit gap limit required.');
assert(isequal(size(raw.accel),[3 count])&&isreal(raw.accel)&&all(isfinite(raw.accel(:)))&& ...
    isequal(size(raw.gyro),[3 count])&&isreal(raw.gyro)&&all(isfinite(raw.gyro(:)))&& ...
    iscell(raw.lineage)&&numel(raw.lineage)==count&&isequal(raw.lineage_times(:),times)&& ...
    all(cellfun(@(x)ischar(x)&&isrow(x)&&~isempty(x),raw.lineage))&&numel(unique(raw.lineage))==count, ...
    'libekf:Lineage','Invalid original inertial samples or provenance.');
assert(isstruct(error_model)&&isscalar(error_model)&&all(isfield(error_model, ...
    {'mean','covariance','state_cross_cov','sample_cross_cov'}))&& ...
    isequal(size(error_model.mean),[12 1])&&isreal(error_model.mean)&&all(isfinite(error_model.mean)), ...
    'libekf:Covariance','Explicit interpolation error mean and joint covariance required.');
R=raw.covariance; U=raw.state_noise_cov; V=error_model.covariance;
E=error_model.state_cross_cov; C=error_model.sample_cross_cov;
assert(isequal(size(P),[42 42])&&isequal(size(R),[6*count 6*count])&& ...
    isequal(size(U),[42 6*count])&&isequal(size(V),[12 12])&& ...
    isequal(size(E),[42 12])&&isequal(size(C),[6*count 12]), ...
    'libekf:Covariance','Invalid interpolation covariance dimensions.');
joint=[P U E;U.' R C;E.' C.' V];
assert(isreal(joint)&&all(isfinite(joint(:)))&&all(diag(joint)>=0)&& ...
    norm(joint-joint.','fro')<=1e-12*max(norm(joint,'fro'),realmin), ...
    'libekf:Covariance','Invalid joint interpolation covariance.');
scale=sqrt(diag(joint)); zero=scale==0;
assert(~any(any(joint(zero,:)~=0)),'libekf:Covariance','Impossible zero-variance dependence.');
scale(zero)=1; normalized=(joint./scale)./scale.';
assert(all(isfinite(normalized(:))),'libekf:Covariance','Interpolation covariance normalization overflow.');
values=eig((normalized+normalized.')/2);
assert(min(values)>=-100*eps*size(joint,1)*max(1,max(abs(values))), ...
    'libekf:Covariance','Inconsistent interpolation error dependence.');
weights=zeros(2,count);
for j=1:2
    exact=find(times==targets(j),1);
    if ~isempty(exact), weights(j,exact)=1; continue; end
    left=find(times<targets(j),1,'last'); right=left+1;
    gap=times(right)-times(left);
    assert(gap<=limits.max_sample_gap,'libekf:Time','Inertial sample gap exceeds the interpolation limit.');
    fraction=(targets(j)-times(left))/gap;
    weights(j,left)=1-fraction; weights(j,right)=fraction;
end
L=kron(weights,eye(6)); samples=[raw.accel;raw.gyro];
values=reshape(L*samples(:)-error_model.mean,6,2);
out=raw; out.accel=values(1:3,:); out.gyro=values(4:6,:); out.epochs=targets;
out.covariance=L*R*L.'+V+L*C+C.'*L.'; out.covariance=(out.covariance+out.covariance.')/2;
out.state_noise_cov=U*L.'+E;
used=any(weights~=0,1); out.lineage=raw.lineage(used); source_epochs=times(used);
out.lineage_times=source_epochs; L=L(:,repelem(used,6));
end
