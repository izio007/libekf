function [out,reference_out]=nav_predict_noise(noise,P,T,N,epochs,W,reference,model)
reference_out=[];
% Сохранённые ошибки данных постоянны; меняется связь с движущимся состоянием.
% W=Cov(новая процессная ошибка, сохранённая ошибка); ноль задаётся явно.
required={'ids','units','mean','covariance','cross_cov','state_times','frame_id'};
assert(isstruct(noise)&&isscalar(noise)&&all(isfield(noise,required))&& ...
    ~isfield(noise,'measurement_cross_cov'),'libekf:Correlation','Invalid stored noise model.');
b=numel(noise.mean); n=size(P,1); next=size(T,1);
assert(b>0&&any(n==[21 42])&&any(next==[21 42])&& ...
    isnumeric(noise.mean)&&isreal(noise.mean)&&isvector(noise.mean)&&all(isfinite(noise.mean(:)))&& ...
    iscell(noise.ids)&&numel(noise.ids)==b&& ...
    all(cellfun(@(x)ischar(x)&&isrow(x)&&~isempty(x),noise.ids))&&numel(unique(noise.ids))==b&& ...
    iscell(noise.units)&&numel(noise.units)==b&& ...
    all(cellfun(@(x)ischar(x)&&isrow(x)&&~isempty(x),noise.units))&& ...
    ischar(noise.frame_id)&&isrow(noise.frame_id)&&~isempty(noise.frame_id)&& ...
    isnumeric(noise.state_times)&&isreal(noise.state_times)&&numel(noise.state_times)==n/21&& ...
    all(isfinite(noise.state_times(:)))&&all(diff(noise.state_times(:))>=0)&& ...
    isnumeric(epochs)&&isreal(epochs)&&numel(epochs)==next/21&& ...
    all(isfinite(epochs(:)))&&all(diff(epochs(:))>=0)&&epochs(end)>=noise.state_times(end), ...
    'libekf:Correlation','Invalid noise identities, units or epochs.');
if isfield(noise,'peer_cross_cov')
    assert(isfield(noise,'peer_time')&&isequal(noise.peer_time,noise.state_times(end))&& ...
        (nargin==8||isequal(epochs(end),noise.peer_time)),'libekf:Correlation', ...
        'Reference/future-error propagation requires a joint reference motion model.');
end
V=noise.covariance; U=noise.cross_cov;
assert(isnumeric(P)&&isnumeric(T)&&isnumeric(N)&&isnumeric(W)&&isnumeric(V)&&isnumeric(U)&& ...
    isequal(size(P),[n n])&&isequal(size(T),[next n])&&isequal(size(N),[next next])&& ...
    isequal(size(W),[next b])&&isequal(size(V),[b b])&&isequal(size(U),[n b])&& ...
    isreal(T)&&all(isfinite(T(:))),'libekf:Correlation','Invalid stored noise dimensions.');
joint=[P U zeros(n,next);U.' V W.';zeros(next,n) W N];
if nargin>=7
    assert(nargin==8&&isfield(noise,'peer_cross_cov')&& ...
        all(isfield(reference,{'ids','t','frame_id','cross_cov','covariance','position'}))&& ...
        all(isfield(noise,{'peer_ids','peer_time'}))&& ...
        isequal(reference.ids(:),noise.peer_ids(:))&&isequal(reference.t,noise.peer_time)&& ...
        strcmp(reference.frame_id,noise.frame_id)&&isfield(model,'future_noise_independent')&& ...
        (isequal(model.future_noise_independent,true)||isequal(model.future_noise_independent,false)),'libekf:Correlation', ...
        'Explicit matching reference and independent reference-process/future-error model required.');
    d=numel(reference.position);
    assert(isequal(size(reference.cross_cov),[n d])&& ...
        isequal(size(reference.covariance),[d d])&&isequal(size(noise.peer_cross_cov),[d b]), ...
        'libekf:Correlation','Invalid joint reference/future-error dimensions.');
    Eprocess=zeros(d,b);
    if isfield(model,'future_noise_cross_cov'), Eprocess=model.future_noise_cross_cov; end
    assert(isnumeric(Eprocess)&&isreal(Eprocess)&&isequal(size(Eprocess),[d b])&&all(isfinite(Eprocess(:)))&& ...
        ((model.future_noise_independent&&all(Eprocess(:)==0))|| ...
        (~model.future_noise_independent&&isfield(model,'future_noise_cross_cov'))), ...
        'libekf:Correlation','Missing or contradictory reference-process/future-error covariance.');
    [reference_out,A,Nref]=nav_predict_reference(reference,T,model);
    assert(reference_out.t==epochs(end),'libekf:Epoch','Reference and navigation propagation end times differ.');
    joint=[P reference.cross_cov U zeros(n,next+d); ...
        reference.cross_cov.' reference.covariance noise.peer_cross_cov zeros(d,next+d); ...
        U.' noise.peer_cross_cov.' V W.' Eprocess.'; ...
        zeros(next,n+d) W N zeros(next,d);zeros(d,n+d) Eprocess zeros(d,next) Nref];
end
assert(isreal(joint)&&all(isfinite(joint(:)))&&all(diag(joint)>=0)&& ...
    norm(joint-joint.','fro')<=1e-12*max(norm(joint,'fro'),realmin), ...
    'libekf:Correlation','Invalid joint state/process/stored-noise covariance.');
d=sqrt(diag(joint)); zero=d==0;
assert(~any(any(joint(zero,:)~=0)),'libekf:Correlation','Impossible zero-variance dependence.');
d(zero)=1; normalized=(joint./d)./d.'; values=eig((normalized+normalized.')/2);
assert(min(values)>=-100*eps*size(joint,1)*max(1,max(abs(values))), ...
    'libekf:Correlation','Inconsistent stored/process-noise dependence.');
out=noise; out.cross_cov=T*U+W; out.state_times=epochs(:);
if nargin==8
    out.peer_cross_cov=A*noise.peer_cross_cov+Eprocess; out.peer_time=reference_out.t;
    assert(all(isfinite(out.peer_cross_cov(:))),'libekf:Correlation','Reference/future-error propagation overflow.');
end
assert(all(isfinite(out.cross_cov(:))),'libekf:Correlation','Noise propagation overflow.');
end
