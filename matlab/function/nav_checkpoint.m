function out=nav_checkpoint(filter)
% Закрыть происхождение отсчётов до времени текущего состояния включительно.
% Новые пакеты обязаны содержать времена всех исходных отсчётов lineage_times.
assert(isstruct(filter)&&isscalar(filter)&&all(isfield(filter,{'state','used','capacity'}))&& ...
    isfield(filter.state,'t')&&isnumeric(filter.state.t)&&isreal(filter.state.t)&& ...
    isscalar(filter.state.t)&&isfinite(filter.state.t)&&iscell(filter.used)&& ...
    all(cellfun(@(x)ischar(x)&&isrow(x)&&~isempty(x),filter.used))&& ...
    isscalar(filter.capacity)&&isfinite(filter.capacity)&&filter.capacity>=numel(filter.used)&& ...
    filter.capacity==floor(filter.capacity),'libekf:History','Invalid checkpoint state or history.');
if isfield(filter,'retired_through')
    assert(isnumeric(filter.retired_through)&&isreal(filter.retired_through)&& ...
        isscalar(filter.retired_through)&&isfinite(filter.retired_through)&& ...
        filter.retired_through<=filter.state.t,'libekf:History','Checkpoint cannot move backwards.');
end
if isfield(filter,'latest_input_epoch')
    assert(isnumeric(filter.latest_input_epoch)&&isreal(filter.latest_input_epoch)&& ...
        isscalar(filter.latest_input_epoch)&&isfinite(filter.latest_input_epoch)&& ...
        filter.latest_input_epoch<=filter.state.t,'libekf:History', ...
        'Cannot retire identifiers of original records newer than the checkpoint epoch.');
end
out=filter;
out.used={}; out.retired_through=filter.state.t;
% Состояние, все ковариации, опоры, запреты и сведения об источниках сохраняются.
end
